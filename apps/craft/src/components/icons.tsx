// The recorder's inline SVG icon set.
//
// Every icon is a static path drawn in `currentColor`, so the colour comes
// from whichever `App.module.css` class the caller passes down. The source
// icons (the ones that label a toggle row) take a `className` because their
// size is set per call site; the action icons — the ones that fill an icon
// button — are `aria-hidden` and sized entirely by their button, so they take
// no props at all.

